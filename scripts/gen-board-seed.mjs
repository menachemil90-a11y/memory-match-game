#!/usr/bin/env node
/** Writes the server seed of built-in board image ids (online play deals from these). */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BOARDS } from './boards.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'supabase/migrations/20261117000002_builtin_boards.sql');
const lit = (s) => `'${s.replace(/'/g, "''")}'`;
const rows = BOARDS.map(
  (b) => `  (${lit(b.id)}, array[${b.items.map(([key]) => lit(`${b.id}/${key}`)).join(', ')}])`,
);
writeFileSync(
  OUT,
  `-- AUTO-GENERATED by scripts/gen-board-seed.mjs — do not edit by hand.
-- Image ids of the built-in boards; the server deals online games from these.
insert into private.builtin_boards (board_id, image_ids) values
${rows.join(',\n')}
on conflict (board_id) do update set image_ids = excluded.image_ids;
`,
);
console.log(`Wrote ${BOARDS.length} boards to ${OUT}`);
